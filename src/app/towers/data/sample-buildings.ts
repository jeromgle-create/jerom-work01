export const SAMPLE_DATA_DAY = "2025-06-30";

export const sampleBuildings: BuildingRecord[] = rows.map((r, i) => {
  const [bldName, bjdCode, bjdName, jibun, useCode, height, floors, useAprDay, lat, lng] = r;
  const [structCode, structName] = STRUCTS[i % STRUCTS.length];
  const isSan = jibun.startsWith("산");
  const [bon, bu = "0"] = jibun.replace("산", "").split("-");
  const archArea = Math.round((40 + ((i * 37) % 400)) * 10) / 10;
  const plat = Math.round(archArea * (2.5 + (i % 5)) * 10) / 10;
  return {
    gisId: `SAMPLE${String(i + 1).padStart(6, "0")}`,
    pnu: `${bjdCode}${isSan ? "2" : "1"}${bon.padStart(4, "0")}${bu.padStart(4, "0")}`,
    bjdCode,
    bjdName,
    jibun,
    useCode,
    useName: USE_NAMES[useCode] ?? "그밖의시설",
    structCode,
    structName,
    archArea,
    useAprDay,
    totArea: Math.round(archArea * Math.max(floors, 1) * 0.9 * 10) / 10,
    platArea: plat,
    height,
    bldName,
    dongName: "",
    grndFloors: floors,
    ugrndFloors: i % 4 === 0 ? 1 : 0,
    dataDay: SAMPLE_DATA_DAY,
    lat,
    lng,
  };
});
